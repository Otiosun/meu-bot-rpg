'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {provisionSeasonLab}=require('../helpers/clover/seasonLabProvisioning');
const {criarBanco}=require('../database');
const {ensurePlayerRecord}=require('../helpers/playerRegistry');
const {getChecklistSummary,renderChecklist,renderWeeklyResetNotice}=require('../helpers/clover/checklistService');
const {getWeeklyPhCapSummary}=require('../helpers/clover/weeklyPhCapService');

test('checklist e lembretes refletem PH de PA e não contam modalidades anuladas',async t=>{
    const dir=await fs.mkdtemp(path.join(os.tmpdir(),'clover-checklist-economy-'));
    let db;
    t.after(async()=>{try{if(db)await db.close();}finally{await fs.rm(dir,{recursive:true,force:true});}});
    const root=path.join(dir,'season');await provisionSeasonLab(root);
    db=await criarBanco({filename:path.join(root,'season.sqlite')});
    const player='checklist-lab';
    await ensurePlayerRecord(db,player,'Personagem fictício');
    const week='2026-11-16',now=new Date(2026,10,20,12,0,0);
    await db.run("INSERT INTO clover_admin_service_payouts(evaluator_id,player_id,points_paid,ph_paid,week_key,source) VALUES(?,?,?,?,?,'salary')",[player,player,24,8,week]);
    let seq=0;
    const up=async(modality,ph,bypass,metadata,rewards)=>db.run("INSERT INTO clover_quick_evaluations(message_key,chat_id,player_id,evaluator_id,modality_key,modality_label,ph_amount,yulls_amount,stars_amount,scene_sent_at,scene_source,evaluated_at,week_key,bypass_weekly_limit,rewards_json,metadata_json) VALUES(?,'lab-group',?,'lab-reviewer',?,?,?,0,0,'2026-11-19 12:00:00','manual','2026-11-19 13:00:00',?,?,?,?)",['lab-'+(++seq),player,modality,modality,ph,week,bypass,JSON.stringify(rewards),JSON.stringify(metadata)]);
    await up('treino_solo',18,0,{},{});
    await up('missao_auto_narrada',5,0,{voided_by_correction:1},{});
    await up('spin_off',60,1,{},{cap:'anulado'});
    await up('missao_desenvolvimento',30,1,{voided_by_correction:1},{});
    const before=await getChecklistSummary(db,player,now);
    assert.equal(before.weekly.commonPh,26);
    assert.equal(before.weekly.autoNarrated,0);
    assert.equal(before.monthly.spinOff,0);
    assert.equal(before.monthly.development,0);
    assert.equal(before.weekly.complete,false);
    assert.equal(before.weekly.commonPh,(await getWeeklyPhCapSummary(db,player,'2026-11-20')).used);
    assert.match(renderChecklist(before,'Teste'),/26\/30/);
    assert.match(renderWeeklyResetNotice(before,'Teste'),/26\/30/);
    await up('missao_auto_narrada',4,0,{},{});
    await up('spin_off',60,1,{},{});
    await up('missao_desenvolvimento',30,1,{},{});
    const after=await getChecklistSummary(db,player,now);
    assert.equal(after.weekly.commonPh,30);
    assert.equal(after.weekly.complete,true);
    assert.equal(after.monthly.complete,true);
    assert.equal(after.streak.weekly,1);
    assert.equal(after.streak.monthly,1);
});
