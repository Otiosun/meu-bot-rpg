function normalizeStatus(value) {
    return String(value || '').trim().toLowerCase();
}

function renderHistoryStatusForPostFicha(player = {}) {
    const status = normalizeStatus(player.historia_status);
    if (['aprovada', 'approved'].includes(status)) return 'aprovada';
    if (['negada', 'rejeitada', 'reprovada', 'rejected'].includes(status)) return 'precisa de ajuste';
    return 'pendente';
}

function renderGameStatusForPostFicha(player = {}) {
    return normalizeStatus(player.jogo_status) === 'liberado' ? 'liberado' : 'bloqueado';
}

